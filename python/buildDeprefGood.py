"""Build the deprefGood class.

Unlike every other class in output30, deprefGood is not generated by an LLM: the
answers are human reference translations taken from the many-references dataset
(Bojar et al., "Scratching the Surface of Possible Translations"), which holds
very many Czech references for the same 50 WMT11 source sentences the rest of
the pipeline translates. It is the "de-preferenced" positive class -- good
translations that owe nothing to any of the raters.

Takes REFS_PER_SENTENCE references for each of the 50 numbered source sentences
in resources/en.txt_unchanged and writes them all into a single file,
resources/output30/deprefGood/all.txt, in the usual prompt/answer block format.
The per-sentence blocks in the datafile are already shuffled by the dataset
authors, so taking the first N of each block is a random sample.

Run from npfl087-otmara/:
    ../v/bin/python3 ./python/buildDeprefGood.py [REFS_PER_SENTENCE] [OUT_FILE]

Both arguments are optional and default to the deprefGood class. Raising the
count and pointing it elsewhere builds a bigger sibling class off the same
references -- that is what buildDeprefGoodBig.py does.

Lowering REFS_PER_SENTENCE only ever drops references off the end of each
sentence's block, so an already-built (and already-measured) class can be cut
down to the new count in place instead of being rebuilt and re-measured --
that is what pruneDeprefGood.py does. It also means the classes built at two
counts nest: deprefGood's units are, sentence by sentence, a prefix of
deprefGoodBig's.
"""
import sys
from pathlib import Path

# 39 rather than the dataset's ~44: the last 5 of each sentence's block are
# dropped. The one sentence with fewer references than this (WMT id 7, "Who is
# Voldemort?", the first line of en.txt_unchanged, which the dataset gives only
# 8 distinct translations) keeps all of them.
REFS_PER_SENTENCE = 39

# Numbered English sources; ids refer to the WMT11 full dataset.
EN_FILE = "./resources/en.txt_unchanged"
# id \t annotators \t interfaces \t tokenized Czech string
DATAFILE = "../many-references-datafile"
# Any good-class file: the prompts are byte-identical across models, and we
# reuse them verbatim so deprefGood units differ from good only in the answer.
PROMPT_SOURCE = "./resources/output30/good/qwen.txt"
OUT_FILE = "./resources/output30/deprefGood/all.txt"

SEP = "-----------------------------"

# The datafile strings are space-tokenized, while every other class holds
# natural Czech; leaving the spacing in would inflate perplexity for a purely
# typographical reason. „ ‚ ( open (no space after), “ ‘ ) and the sentence
# punctuation close (no space before). The ASCII " is ambiguous, so its role
# alternates within each sentence.
NO_SPACE_BEFORE = set(',.!?;:)]}»…“‘')
NO_SPACE_AFTER = set('([{«„‚')


def detokenize(tokenized):
  out = []
  quote_open = False
  suppress_next = True  # no space before the first token
  for tok in tokenized.split():
    lead = tok[0]
    if suppress_next:
      space = False
    elif lead == '"':
      space = not quote_open  # a closing " glues to the previous token
    elif lead in NO_SPACE_BEFORE:
      space = False
    else:
      space = True

    for ch in tok:
      if ch == '"':
        quote_open = not quote_open

    trail = tok[-1]
    if trail == '"':
      suppress_next = quote_open  # it just opened -> glue the next token
    else:
      suppress_next = trail in NO_SPACE_AFTER

    out.append((" " if space else "") + tok)
  return "".join(out)


def getSentenceIds(path):
  ids = []
  with open(path, encoding="utf-8") as file:
    for line in file:
      if line.strip():
        ids.append(line.split("\t", 1)[0].strip())
  return ids


def getReferences(path, ids, perSentence):
  """First `perSentence` references per id, in one streaming pass."""
  refs = {i: [] for i in ids}
  wanted = set(ids)
  full = 0
  with open(path, encoding="utf-8") as file:
    for line in file:
      parts = line.rstrip("\n").split("\t")
      if len(parts) < 4 or parts[0] not in wanted:
        continue
      bucket = refs[parts[0]]
      if len(bucket) < perSentence:
        bucket.append(parts[3])
        if len(bucket) == perSentence:
          full += 1
          if full == len(wanted):
            break
  return refs


def getPrompts(path):
  """One prompt per source sentence, verbatim from a good-class file.

  Those files hold 50 groups of 3 units, one group per source sentence in
  en.txt_unchanged order, with the same prompt inside each group.
  """
  units = [u for u in open(path, encoding="utf-8").read().split(SEP) if u.strip()]
  if len(units) != 150:
    sys.exit("expected 150 units in " + path + ", got " + str(len(units)))
  prompts = []
  for g in range(50):
    group = [units[g * 3 + k].split("\nanswer:\n")[0].lstrip("\n") for k in range(3)]
    if not group[0] == group[1] == group[2]:
      sys.exit("prompts differ inside group " + str(g) + " of " + path)
    prompts.append(group[0])
  return prompts


def build(perSentence=REFS_PER_SENTENCE, outFile=OUT_FILE):
  ids = getSentenceIds(EN_FILE)
  prompts = getPrompts(PROMPT_SOURCE)
  refs = getReferences(DATAFILE, ids, perSentence)

  blocks = []
  for sentenceId, prompt in zip(ids, prompts):
    # WMT id 7 ("Who is Voldemort?", the first line of en.txt_unchanged) is
    # short enough that the dataset holds only 8 distinct references for it, so
    # it contributes fewer than perSentence units. It is the only one to do so
    # at 39; at deprefGoodBig's 1000, seven more sentences join it.
    if len(refs[sentenceId]) < perSentence:
      print("only " + str(len(refs[sentenceId])) + " references for sentence "
            + sentenceId, file=sys.stderr)
    for cs in refs[sentenceId]:
      blocks.append(prompt + "\nanswer:\n" + '"cs: "' + detokenize(cs) + '""')

  out = Path(outFile)
  out.parent.mkdir(parents=True, exist_ok=True)
  with out.open("w", encoding="utf-8") as file:
    file.write(("\n" + SEP + "\n").join(blocks) + "\n")

  print("units: " + str(len(blocks)))
  return len(blocks)


def main():
  perSentence = int(sys.argv[1]) if len(sys.argv) > 1 else REFS_PER_SENTENCE
  outFile = sys.argv[2] if len(sys.argv) > 2 else OUT_FILE
  build(perSentence, outFile)


if __name__ == "__main__":
  main()
